// Generates src/engine/canonicalFace.ts from MediaPipe's canonical_face_model.obj
// (mediapipe/modules/face_geometry/data/canonical_face_model.obj, Apache-2.0).
// Units are centimetres; +x = subject's left, +y = up, +z = out of the face.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const lines = readFileSync(join(here, 'canonical_face_model.obj'), 'utf8').split('\n');
const pos = [];
const idx = [];
for (const l of lines) {
  const p = l.trim().split(/\s+/);
  if (p[0] === 'v') pos.push(...p.slice(1, 4).map((n) => +(+n).toFixed(4)));
  if (p[0] === 'f') idx.push(...p.slice(1, 4).map((t) => parseInt(t, 10) - 1));
}
if (pos.length !== 468 * 3) throw new Error(`unexpected vertex count ${pos.length / 3}`);
const out = `// AUTO-GENERATED by scripts/gen-canonical-face.mjs — do not edit.
// MediaPipe canonical face model (Apache-2.0). Units: cm. +x = subject's left, +y = up, +z = toward camera.
export const CANONICAL_VERTEX_COUNT = 468;
// prettier-ignore
export const CANONICAL_POSITIONS = new Float32Array([${pos.join(',')}]);
// prettier-ignore
export const CANONICAL_TRIANGLES = new Uint16Array([${idx.join(',')}]);
`;
writeFileSync(join(here, '../src/engine/canonicalFace.ts'), out);
console.log(`wrote ${pos.length / 3} vertices, ${idx.length / 3} triangles`);
